"""Compile external donation QR images into a local JavaScript module.

The source tree and package intentionally contain no standalone QR image.
Originals live outside the source tree and are embedded as data URIs.
"""

import base64
import json
import os
import sys

IMAGES = {
    "wechat": ("微信.jpg", "wechat.jpg", "wechat.png"),
    "alipay": ("支付宝.jpg", "alipay.jpg", "alipay.png"),
}
DEFAULT_SOURCE_DIR = "/vol1/1000/软件开发/收款码"
OUTPUT = os.path.join("app", "ui", "donate-qr.js")
MIME = {
    ".png": "image/png",
    ".jpg": "image/jpeg",
    ".jpeg": "image/jpeg",
    ".gif": "image/gif",
    ".webp": "image/webp",
}
HEADER = """\
/* SPDX-License-Identifier: GPL-3.0-or-later
 * Copyright (C) 2026 LiuFudi
 *
 * GENERATED by tools/make_donate_qr.py -- do not edit by hand.
 * Donation QR codes are inlined as data URIs; no standalone image is shipped.
 */
window.__SRIOV_DONATE_QR__ = {
"""


def mime_for(path):
    return MIME.get(os.path.splitext(path)[1].lower(), "application/octet-stream")


def find_source(source_dir, names):
    for name in names:
        path = os.path.join(source_dir, name)
        if os.path.isfile(path):
            return path
    return None


def build(source_dir):
    entries = []
    for key in sorted(IMAGES):
        path = find_source(source_dir, IMAGES[key])
        if path is None:
            raise OSError("missing %s (%s)" % (" / ".join(IMAGES[key]), source_dir))
        with open(path, "rb") as handle:
            encoded = base64.b64encode(handle.read()).decode("ascii")
        entries.append((key, "data:%s;base64,%s" % (mime_for(path), encoded)))

    chunks = [HEADER]
    for position, (key, uri) in enumerate(entries):
        comma = "," if position + 1 < len(entries) else ""
        chunks.append("  %s: %s%s\n" % (json.dumps(key), json.dumps(uri), comma))
    chunks.append("};\n")
    return "".join(chunks)


def main(argv):
    root = os.path.abspath(argv[1]) if len(argv) > 1 else os.path.dirname(
        os.path.dirname(os.path.abspath(__file__)))
    source_dir = os.path.abspath(
        argv[2] if len(argv) > 2 else os.environ.get("SRIOV_QR_DIR", DEFAULT_SOURCE_DIR))
    target = os.path.join(root, OUTPUT)
    try:
        text = build(source_dir)
    except OSError as exc:
        if os.path.isfile(target):
            print("make_donate_qr: source unavailable (%s); keeping %s" % (exc, OUTPUT))
            return 0
        sys.stderr.write("make_donate_qr: %s\n" % exc)
        return 1

    try:
        with open(target, "r", encoding="utf-8") as handle:
            if handle.read() == text:
                print("make_donate_qr: %s already up to date" % OUTPUT)
                return 0
    except OSError:
        pass
    os.makedirs(os.path.dirname(target), exist_ok=True)
    with open(target, "w", encoding="utf-8") as handle:
        handle.write(text)
    print("make_donate_qr: wrote %s (%d bytes)" % (OUTPUT, len(text)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
